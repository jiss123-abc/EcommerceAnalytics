select*from customers;select*from order_items;select*from orders;select*from products;
-- Step 5.1: Repeat Customer Analysis
-- Purpose: Identify customers who have placed more than one order
-- to understand repeat purchasing behavior and customer loyalty.
select c.customer_id,c.customer_name,count(o.order_id) as total_orders from customers c join orders o on o.customer_id=c.customer_id 
group by c.customer_id,c.customer_name having count(c.customer_id)>1

-- Step 5.2: Customer Purchase Frequency
-- Purpose: Calculate the total number of orders placed by each customer
-- to understand customer purchasing frequency and engagement.
select c.customer_id,c.customer_name,count(o.order_id) as total_orders from customers c 
join orders o on o.customer_id=c.customer_id group by c.customer_id,c.customer_name order by total_orders desc

-- Step 5.3: Monthly Revenue Growth
-- Purpose: Calculate monthly delivered revenue and compare it
-- with the previous month to identify revenue growth or decline.
select months,years,revenue,lag(revenue) over(order by months,years) as previous_year 
from (select month(o.order_date) as months,year(o.order_date) as years,sum(oi.unit_price*oi.quantity) as revenue
from orders o join order_items oi on oi.order_id=o.order_id where o.order_status='Delivered' 
group by month(o.order_date),year(o.order_date) )as monthly_sales

-- Step 5.4: Product Performance Ranking
-- Purpose: Rank products by total revenue generated from delivered orders
-- to identify the highest-performing products.
select product_id,product_name,total_revenue,rank() over(order by total_revenue desc) as revenue_rank from
(select p.product_id,p.product_name,sum(oi.unit_price*oi.quantity) as total_revenue from products p 
join order_items oi on oi.product_id=p.product_id join orders o on o.order_id=oi.order_id where o.order_status='Delivered'
group by p.product_id, p.product_name) as product_sales

-- Step 5.5: Customer Revenue Ranking
-- Purpose: Rank customers by total spending on delivered orders
-- to identify the highest-value customers.
select customer_id,customer_name,total_revenue,rank() over(order by total_revenue desc) as revenue_rank from
(select c.customer_id,c.customer_name,sum(oi.unit_price*oi.quantity) as total_revenue from customers c 
join orders o on o.customer_id=c.customer_id join order_items oi on oi.order_id=o.order_id where o.order_status='Delivered' 
group by c.customer_id,c.customer_name) as customer_revenue_ranking

-- Step 5.6: Running Total Revenue
-- Purpose: Calculate cumulative delivered revenue over time
-- to track how total sales accumulate across orders.
select order_date,daily_revenue,sum(daily_revenue) over(order by order_date) as running_total_revenue from
(select o.order_date,sum(oi.unit_price*oi.quantity) as daily_revenue from orders o join order_items oi on oi.order_id=o.order_id
where o.order_status='Delivered' group by o.order_date) as revenue_over_time

-- Step 5.7: Customer Retention Analysis
-- Purpose: Identify customers who placed orders in multiple months
-- to understand repeat purchasing behavior and customer retention.
select c.customer_id,c.customer_name,count(distinct year(o.order_date)*100+month(o.order_date)) as distinct_months
from customers c join orders o on o.customer_id=c.customer_id where o.order_status='Delivered' group by c.customer_id,c.customer_name  
having count(distinct year(o.order_date) * 100 + month(o.order_date)) > 1;

-- Step 5.8: Customer Lifetime Value (CLV)
-- Purpose: Calculate the total revenue generated by each customer
-- using delivered orders only, to identify the most valuable customers.
select c.customer_id,c.customer_name,sum(oi.unit_price*oi.quantity) as total_revenue from customers c 
join orders o on o.customer_id=c.customer_id join order_items oi on o.order_id=oi.order_id	
where o.order_status='Delivered' group by c.customer_id,c.customer_name order by total_revenue desc

-- Step 5.9: Revenue Contribution by Product Category
-- Purpose: Calculate total revenue generated by each product category
-- using delivered orders only, to identify the highest-revenue categories.
select p.category,sum(oi.quantity * oi.unit_price) as total_revenue from products p join order_items oi on oi.product_id=p.product_id 
join orders o on o.order_id=oi.order_id where o.order_status='Delivered' group by p.category order by total_revenue desc

-- Step 5.10: Percentage Revenue Contribution by Product Category
-- Purpose: Calculate each product category's percentage of total delivered revenue
-- to identify which categories contribute most to overall sales.
select p.category,100.0*(sum(oi.quantity * oi.unit_price)/(select sum(oi.quantity * oi.unit_price) from orders o 
join order_items oi on oi.order_id=o.order_id where order_status='Delivered')) as revenue_contribution from products p 
join order_items oi on oi.product_id=p.product_id join orders o on o.order_id=oi.order_id where o.order_status='Delivered' 
group by p.category order by revenue_contribution desc

-- Step 5.11: Order Cancellation Rate Analysis
-- Purpose: Calculate the percentage of orders that were cancelled
-- to evaluate the order cancellation rate and identify potential issues.
select 100.0*sum(case when order_status='Cancelled' then 1 else 0 end)/nullif(count(*),0) as order_cancelation_percentile         
from orders 

-- Step 5.12: Order Status Distribution
-- Purpose: Calculate the total number and percentage of orders
-- in each status (Delivered, Cancelled, and Pending)
-- to understand the overall distribution of order statuses.
select order_status,100.0*count(*)/(select count(*) from orders) as status_percentage from orders group by order_status

-- Step 5.13: High-Value Order Analysis
-- Purpose: Identify delivered orders with a total value greater than ₹30,000
-- to understand which transactions contribute significant revenue.
select o.order_id,o.order_date,sum(oi.quantity * oi.unit_price) as total from orders o join order_items oi on oi.order_id=o.order_id
where o.order_status='Delivered' group by o.order_id,o.order_date having sum(oi.quantity * oi.unit_price)>30000

-- Step 5.14: Average Order Value by Month
-- Purpose: Calculate the average value of delivered orders for each month
-- to identify changes in monthly customer spending.
select year,month,avg(total) as average from 
(select o.order_id,year(o.order_date) as year,month(o.order_date) as month,sum(oi.quantity * oi.unit_price) as total from orders o 
join order_items oi on oi.order_id=o.order_id where o.order_status='Delivered' 
group by o.order_id,year(o.order_date),month(o.order_date))as monthly_order group by year,month